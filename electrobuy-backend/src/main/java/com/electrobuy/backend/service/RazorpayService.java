package com.electrobuy.backend.service;

import com.razorpay.Order;
import com.razorpay.RazorpayClient;
import com.razorpay.Refund;
import com.razorpay.Utils;
import lombok.RequiredArgsConstructor;
import org.json.JSONObject;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;

import java.util.Optional;
import java.util.UUID;

/**
 * Enterprise service acting as a unified wrapper around the Razorpay Client
 * SDK.
 * Handles order tokens, cryptographic HMAC SHA256 signature verifications,
 * and initiates financial refunds. Supports seamless offline mock fallbacks.
 */
@Service
@RequiredArgsConstructor
public class RazorpayService {

    private final Optional<RazorpayClient> razorpayClientOptional;
    private final AuditLogService auditLogService;

    @Value("${razorpay.api.secret}")
    private String apiSecret;

    @Value("${razorpay.mock.enabled:true}")
    private boolean mockMode;

    /**
     * Helper method to safely retrieve the RazorpayClient if present.
     */
    private RazorpayClient getRazorpayClient() {
        return razorpayClientOptional.orElse(null);
    }

    /**
     * Standardizes checkout payment order creation.
     * Generates a payment intent token (order_ID) from Razorpay's servers.
     * * @param amount The total transaction amount in Rupees (e.g., 29999.00)
     * 
     * @param receiptId A unique tracking string associated with the local order
     *                  index
     * @return The unique order ID generated by the gateway
     */
    public String createRazorpayOrder(double amount, String receiptId) {
        // Razorpay API reads transaction values in the smallest currency division
        // (Paise for INR)
        long amountInPaise = Math.round(amount * 100);
        RazorpayClient razorpayClient = getRazorpayClient();

        if (mockMode || razorpayClient == null) {
            String mockOrderId = "mock_order_" + UUID.randomUUID().toString().replace("-", "").substring(0, 14);
            auditLogService.logAction(
                    "PAYMENT_INTENT_MOCKED",
                    "[MOCK] Generated offline order tracking ID: " + mockOrderId + " for amount: " + amount);
            return mockOrderId;
        }

        try {
            JSONObject orderRequest = new JSONObject();
            orderRequest.put("amount", amountInPaise);
            orderRequest.put("currency", "INR");
            orderRequest.put("receipt", receiptId);

            Order razorpayOrder = razorpayClient.orders.create(orderRequest);
            return razorpayOrder.get("id");
        } catch (Exception e) {
            throw new RuntimeException("Failed to register payment intent with Razorpay Gateway: " + e.getMessage());
        }
    }

    /**
     * Checks the cryptographic integrity of checkout signatures.
     * Re-computes the HMAC-SHA256 signature locally using your private webhook/API
     * secret.
     */
    public boolean verifySignature(String razorpayOrderId, String razorpayPaymentId, String signature) {
        if (mockMode) {
            auditLogService.logAction("SIGNATURE_VERIFIED_MOCK", "[MOCK] Bypassing cryptographic validation.");
            return true;
        }

        try {
            JSONObject options = new JSONObject();
            options.put("razorpay_order_id", razorpayOrderId);
            options.put("razorpay_payment_id", razorpayPaymentId);
            options.put("razorpay_signature", signature);

            return Utils.verifyPaymentSignature(options, apiSecret);
        } catch (Exception e) {
            auditLogService.logAction("SIGNATURE_VERIFICATION_FAILED",
                    "Cryptographic verify failed with error: " + e.getMessage());
            return false;
        }
    }

    /**
     * Initiates a safe, return-to-source refund request for a completed payment.
     * * @param razorpayPaymentId The actual payment settlement ID (starts with
     * "pay_")
     * 
     * @param amount          The value in Rupees to return to the customer
     * @param refundReceiptId A unique tracking string for the refund
     * @return The unique refund transaction ID returned by the gateway
     */
    public String processRefund(String razorpayPaymentId, double amount, String refundReceiptId) {
        long amountInPaise = Math.round(amount * 100);
        RazorpayClient razorpayClient = getRazorpayClient();

        if (mockMode || razorpayClient == null) {
            String mockRefundId = "mock_rfnd_" + UUID.randomUUID().toString().replace("-", "").substring(0, 14);
            auditLogService.logAction(
                    "REFUND_MOCKED",
                    "[MOCK] Initiated offline refund: " + mockRefundId + " (Amt: " + amount + " INR) for payment: "
                            + razorpayPaymentId);
            return mockRefundId;
        }

        try {
            JSONObject refundRequest = new JSONObject();
            refundRequest.put("payment_id", razorpayPaymentId);
            refundRequest.put("amount", amountInPaise);
            refundRequest.put("speed", "normal");

            JSONObject notes = new JSONObject();
            notes.put("refund_receipt_id", refundReceiptId);
            refundRequest.put("notes", notes);

            Refund refund = razorpayClient.refunds.create(refundRequest);
            return refund.get("id");
        } catch (Exception e) {
            throw new RuntimeException("Failed to process refund request with Razorpay Gateway: " + e.getMessage());
        }
    }
}